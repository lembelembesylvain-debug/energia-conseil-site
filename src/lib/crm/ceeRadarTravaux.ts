export function mwhCumacDepuisEuros(euros: number) {
  return Math.round(euros / COURS_EMMY_CLASSIQUE_EUR);
}

export function volumeCumacDepuisEuros(minEur: number, maxEur: number) {
  const min = mwhCumacDepuisEuros(minEur);
  const max = mwhCumacDepuisEuros(maxEur);
  const fmt = (n: number) => n.toLocaleString("fr-FR");
  return min === max ? `~${fmt(min)} MWh cumac` : `${fmt(min)} à ${fmt(max)} MWh cumac`;
}

export function estimationCentraleEur(fiche: Pick<CeeFicheTravaux, "estimationMinEur" | "estimationMaxEur">) {
  return Math.round((fiche.estimationMinEur + fiche.estimationMaxEur) / 2);
}

