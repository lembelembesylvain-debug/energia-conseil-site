export const PRESTATIONS_MARCHE_2026: PrestationCatalogue[] = DEFS_PRESTATIONS_MARCHE.map(creerPrestationMarche);

export function avecReferenceMarche(prestation: PrestationCatalogue): PrestationCatalogue {
  if (prestation.demo) return prestation;
  const referenceMarche = REFERENCES_MARCHE_PAR_ID[prestation.id];
  if (!referenceMarche) return prestation;
  const notes = prestation.notes.includes("repères indicatifs")
    ? prestation.notes
    : `${prestation.notes}\n${AVERTISSEMENT_TARIF_MARCHE}`.trim();
  return {
    ...prestation,
    referenceMarche,
    structurePrixInterne: structurePrixInterneVide(referenceMarche.priceMedianHT),
    dateMiseAJour: referenceMarche.lastReviewedAt,
    notes,
  };
}

export function listerToutesReferencesMarche(): {
  prestationId: string;
  nom: string;
  reference: ReferenceMarche;
}[] {
  const depuisExistantes = Object.entries(REFERENCES_MARCHE_PAR_ID).map(([prestationId, reference]) => ({
    prestationId,
    nom: prestationId,
    reference,
  }));
  const depuisNouvelles = PRESTATIONS_MARCHE_2026.map((item) => ({
    prestationId: item.id,
    nom: item.nom,
    reference: item.referenceMarche as ReferenceMarche,
  }));
  return [...depuisExistantes, ...depuisNouvelles];
}
